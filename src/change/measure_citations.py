"""Measure how well the fixed citation queries of src/change/assess.py find their accepted section (Step 22e).

For every (field, query, accepted section) in FIELD_CITATIONS the query is run once and the rank of the first hit
from the accepted section is recorded (hit@10 means rank 1 to 10).
There is one fixed query per requirement, so each cell
is a single hit or miss with a rank, not a rate. Nothing here changes the queries: they were fixed before this was run.

Run from the repo root (needs sentence-transformers and the cached or rebuilt dense index):
    python -m src.change.measure_citations --out reports/step22_e_table.md
"""
from __future__ import annotations

import argparse
from pathlib import Path

from src.change.assess import FIELD_CITATIONS
from src.checker.citations import find_citation
from src.common.schemas import Chunk
from src.ir.base import Retriever

K = 10


def measure(retriever: Retriever, chunks: dict[str, Chunk], k: int = K) -> list[dict[str, object]]:
    """One row per (field, spec): the rank of the first accepted-section hit within the top k, or None."""
    rows: list[dict[str, object]] = []
    for field, specs in FIELD_CITATIONS.items():
        for spec in specs:
            citation = find_citation(spec, retriever, chunks, k)
            rows.append({
                "field": field, "section": sorted(spec.sections)[0], "query": spec.query,
                "rank": citation.rank if citation else None, "chunk_id": citation.chunk_id if citation else "",
            })
    return rows


def table(name: str, rows: list[dict[str, object]], k: int = K) -> str:
    """Markdown table for one retriever."""
    hits = sum(1 for r in rows if r["rank"] is not None)
    lines = [f"### {name}", "", f"hit@{k}: {hits} of {len(rows)} requirements", "",
             "| Field | Accepted section | Rank of first accepted hit | Chunk cited |", "|---|---|---|---|"]
    for r in rows:
        rank = r["rank"] if r["rank"] is not None else f"miss (not in top {k})"
        lines.append(f"| {r['field']} | {r['section']} | {rank} | {r['chunk_id'] or '-'} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Run the measurement for the frozen Step 18 system (E5b) and the checker's default (plain hybrid RRF)."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="reports/step22_e_table.md")
    args = parser.parse_args()
    from src.checker.retrieval import default_retriever, module_chunks
    from src.checker.settings import RetrievalSettings
    from src.ir.step18_config import e5b
    from src.ir.step18_systems import Context18

    chunks = module_chunks("device")
    frozen = Context18(list(chunks.values())).build(e5b())
    default = default_retriever(RetrievalSettings())
    parts = [
        "# Citation hit@10 per field (generated by src/change/measure_citations.py)\n",
        table("Frozen Step 18 config E5b (stemmed BM25 + bge-large with prefix and headings, RRF), device chunks",
              measure(frozen, chunks)),
        table("Checker default (plain hybrid RRF: BM25 + bge-small), device chunks", measure(default, chunks)),
    ]
    Path(args.out).write_text("\n".join(parts), encoding="utf-8")
    print("\n".join(parts))


if __name__ == "__main__":
    main()
