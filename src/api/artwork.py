"""Real generateArtwork, getArtwork, getExports and downloadArtifact (Step 24b).

Flow of `generateArtwork`:
1. `prepare` runs in the request. It checks the change and label, reads the confirmed assessment, decides the
   barcode (KEEP, REGENERATE or NEEDS_INPUT with the change rules), revises the template and record with the
   renderer's engine, and fills the template. Every refusal (change_closed, change_not_confirmed, needs_input,
   layout failure ...) is answered here, before any job exists and before anything is written.
2. `run_generate_job` runs in the background. It renders the PDF, SVG, QR and a report, stores each file once as
   `artifacts/<sha256>.<ext>` (temp file, then rename), and appends every row in ONE transaction: the new product
   version, the new template version, the new draft label version (never an edit of an old one), the layout
   check, the GeneratedArtwork row and one Artifact row per file.

`artifact_sha256` of a version is the sha256 of its PDF bytes (the file that is printed). Approval binds to it.
Nothing here approves, publishes or invents an identifier.
"""

