NEEDS_TITLES = {"udi_di": "Enter the allocated UDI-DI (never generated by LabelLens)"}


class NeedsInput(ApiError):
    """409 `needs_input`: the barcode cannot be decided without a person. No artwork is produced."""

    def __init__(self, decision: dict[str, Any]) -> None:
        super().__init__(409, "needs_input", decision["reason"])
        self.decision = decision

    def body(self) -> dict[str, Any]:
        """The contract's NeedsInput body: a BarcodeDecision plus the task that unblocks it."""
        needed = self.decision.get("required_identifier") or "udi_di"
        title = NEEDS_TITLES.get(needed) or f"Resolve {needed.removeprefix('confirm_')}"
        if needed.startswith("confirm_"):
            title = f"Confirm the change to {needed.removeprefix('confirm_')} before a new barcode is drawn"
        return {"error": "needs_input", "message": self.message, "barcode_decision": self.decision,
                "task": {"task_id": f"task_{needed}", "title": title}}


class LayoutRefused(ApiError):
    """422 `layout_failed`: the template does not fit. The body is a CheckResult of kind layout (the contract)."""

    def __init__(self, check: dict[str, Any], message: str) -> None:
        super().__init__(422, "layout_failed", message)
        self.check = check

    def body(self) -> dict[str, Any]:
        """The stored layout CheckResult."""
        return self.check


# ---------------------------------------------------------------- files


def artifacts_root(files: Path) -> Path:
    """The artifact folder, created on demand."""
    root = files / ARTIFACT_DIR
    root.mkdir(parents=True, exist_ok=True)
    return root


def store_file(root: Path, data: bytes, ext: str) -> str:
    """Write `data` once as `<sha256>.<ext>` (temp file, then atomic rename). Returns the sha256."""
    sha = hashlib.sha256(data).hexdigest()
    target = root / f"{sha}.{ext}"
    if not target.exists():
        temp = root / f".{sha}.{ext}.{os.getpid()}.{new_id('tmp')}.tmp"
        temp.write_bytes(data)
        os.replace(temp, target)
    return sha


def public_base_url() -> str:
    """Where a published page would live (a placeholder unless LABELLENS_PUBLIC_BASE_URL is set)."""
    return os.environ.get("LABELLENS_PUBLIC_BASE_URL", DEFAULT_PUBLIC_BASE).rstrip("/")


# ---------------------------------------------------------------- planning (in the request)


@dataclass
class Plan:
    """Everything the background job needs, decided in the request."""

    artwork_id: str
    version_id: str
    change_id: str
    label_id: str
    product_id: str
    user_id: str
    test_data: bool
    assessment_id: str | None
    revision: Revision
    decision: dict[str, Any]
    change_log: list[dict[str, Any]]
    base_product_version: int  # the product version the edit was applied to
    reuse_product_version: int | None  # a version this change already made (regeneration)
    template_id: str
    template_version: int  # the template version the revision started from (the new one is this plus one)
    qr_payload: str


def _record_of(row: ProductVersion) -> ProductRecord:
    return changes._record(row)


def _current_product(session: Session, product_id: str) -> ProductVersion:
    row = session.scalars(
        select(ProductVersion).where(ProductVersion.product_id == product_id).order_by(ProductVersion.version.desc())
    ).first()
    if row is None:
        raise ApiError(404, "not_found", f"No product {product_id!r}.")
    return row


def _edits(change: ChangeRequest, assessment: ChangeAssessment | None) -> list[dict[str, str]]:
    """The validated edits: the stored assessment's when there is one, else the change row's own."""
    if assessment is not None:
        if assessment.payload["parser"] == "not_implemented" or not assessment.payload["items"]:
            raise ApiError(409, "nothing_assessed", "Nothing was assessed for this change, so nothing can be made.")
        return [dict(e) for e in assessment.payload["edits"]]
    first = {"field": change.field, "old_value": change.old_value, "new_value": change.new_value}
    return [first] + [dict(e) for e in change.edits]


def _template_for(session: Session, product_id: str, family: list[LabelVersion]) -> LabelTemplate:
    """The latest version of the label's template; an uploaded label with none uses the product's only template."""
    pinned = next((v.template_id for v in reversed(family) if v.template_id), None)
    stmt = select(LabelTemplate).where(LabelTemplate.product_id == product_id)
    if pinned:
        stmt = stmt.where(LabelTemplate.template_id == pinned)
    rows = list(session.scalars(stmt.order_by(LabelTemplate.seq)))
    latest: dict[str, LabelTemplate] = {}
    for row in rows:
        latest[row.template_id] = row
    if len(latest) == 1:
        return next(iter(latest.values()))
    if not latest:
        raise ApiError(409, "template_required", "This product has no template yet. Register one first.")
    ids = sorted(latest)
    message = "The label has no template and the product has several."
    raise ApiError(409, "template_required", message, {"template_ids": ids})


def _decision_json(outcome: BarcodeOutcome) -> dict[str, Any]:
    return outcome.to_json()


def _layout_error(session: Session, template_id: str, failure: LayoutFailure, user_id: str) -> LayoutRefused:
    """422 with a CheckResult (kind layout) for the template, stored so the failure is on record."""
    finding = {
        "flag_id": new_id("flg"), "kind": failure.kind or "layout", "severity": "critical", "message": failure.message,
        "evidence_chunk_ids": [], "confidence": 1.0, "needs_human": False,
    }
    if failure.slot:
        finding["observed"] = failure.slot
    row = add_check_result(session, "layout", [finding], template_id=template_id, user_id=user_id)
    return LayoutRefused(checks.check_result_json(row), failure.message)


def prepare(
    session: Session, engine: ArtworkEngine, user: User, change_id: str, label_id: str, test_data: bool
) -> Plan:
    """Decide everything for one generation, or raise the contract's error. Writes only a failed layout check."""
    change = session.get(ChangeRequest, change_id)
    if change is None:
        raise ApiError(404, "not_found", f"No change {change_id!r}.")
    if is_closed(session, change_id):
        raise ApiError(409, "change_closed", "This change was rejected. Create a new change request.")
    family = list(session.scalars(
        select(LabelVersion).where(LabelVersion.label_id == label_id).order_by(LabelVersion.artwork_version)
    ))
    if not family:
        raise ApiError(404, "not_found", f"No label {label_id!r}.")
    if family[0].product_id != change.product_id:
        raise ApiError(409, "label_product_mismatch", f"Label {label_id!r} belongs to another product.")
    assessment = changes.latest_assessment(session, change_id)
    edits = _edits(change, assessment)
    fields = sorted(e["field"] for e in edits)
    if len(edits) == 1:
        main = edits[0]
        allocated = None
    elif fields == ["model", "udi_di"]:  # a model change together with the identifier allocated for it
        main = next(e for e in edits if e["field"] == "model")
        allocated = next(e for e in edits if e["field"] == "udi_di")["new_value"]
    else:
        raise ApiError(
            422, "unsupported_edits",
            "One generation handles one edit, or a model edit together with its new udi_di. Split the change.",
            {"fields": fields},
        )

    # the record the edit applies to: the one before this change, so a regeneration starts from the same place
    product_id = change.product_id
    applied = session.scalars(select(ProductVersion).where(
        ProductVersion.product_id == product_id, ProductVersion.source_change_id == change_id)).first()
    base_row = _current_product(session, product_id)
    if applied is not None:
        base_row = session.scalars(select(ProductVersion).where(
            ProductVersion.product_id == product_id, ProductVersion.version == applied.supersedes_version)).one()
    base_record = _record_of(base_row)
    old_values = record_values(base_record)
    new_values = {**old_values, **{e["field"]: e["new_value"] for e in edits}}
    template_row = _template_for(session, product_id, family)
    barcode_slots = [s for s in template_row.slots if s["type"] == "barcode"]
    if len(barcode_slots) != 1:
        raise ApiError(422, "unsupported_template", "Exactly one GS1 barcode slot is supported.")
    confirmed = bool(assessment and assessment.confirmed)
    outcome = decide_change_barcode(
        old_values, new_values, [e["field"] for e in edits], symbology=barcode_slots[0]["symbology"],
        confirmed=confirmed,
    )
    if outcome.decision == "NEEDS_INPUT":
        raise NeedsInput(_decision_json(outcome))
    if assessment is not None and not confirmed:
        raise ApiError(409, "change_not_confirmed", "The change was assessed but nobody has confirmed it yet.")

    template = {
        "template_id": template_row.template_id, "version": template_row.version, "product_id": product_id,
        "size_mm": {"w": template_row.size_w, "h": template_row.size_h}, "background": template_row.background,
        "slots": [dict(s) for s in template_row.slots],
    }
    if template_row.min_font_pt is not None:
        template["min_font_pt"] = template_row.min_font_pt
    version_id = new_id("lbv")
    steps = "; ".join(f"{e['field']} {e['old_value']!r} to {e['new_value']!r}" for e in edits)
    reason = f"Change {change_id}: {steps}"
    flags = {CONFIRM_FLAG[e["field"]]: True for e in edits if e["field"] in ENCODED_FIELDS and confirmed}
    old_value = main["old_value"] or old_values.get(main["field"], "")
    try:
        revision = engine.revise(
            template, base_record,
            {"change_id": change_id, "product_id": product_id, "field": main["field"], "old_value": old_value,
             "new_value": main["new_value"]},
            version_id=version_id, previous_version_id=family[-1].version_id, actor=user.user_id, reason=reason,
            test_data=test_data, confirmed=flags, requires_new_identifier=allocated is not None,
            allocated_identifier=allocated,
        )
    except IdentifierRequired as error:
        decision = {"decision": "NEEDS_INPUT", "old_payload": _payload(old_values), "new_payload": "",
                    "symbology": barcode_slots[0]["symbology"], "reason": str(error), "required_identifier": "udi_di"}
        raise NeedsInput(decision) from error
    except LayoutFailure as failure:
        raise _layout_error(session, template_row.template_id, failure, user.user_id) from failure
    except RendererUnavailable as error:
        raise ApiError(503, "renderer_unavailable", str(error)) from error
    except ValueError as error:
        raise _refusal(error) from error
    if revision.action == "NEEDS_INPUT" or revision.label is None:
        decision = {"decision": "NEEDS_INPUT", "old_payload": _payload(old_values), "new_payload": "",
                    "symbology": barcode_slots[0]["symbology"], "reason": revision.reason,
                    "required_identifier": revision.required_identifier or "udi_di"}
        raise NeedsInput(decision)
    if revision.action != outcome.decision:  # two engines disagree: refuse rather than pick one
        raise ApiError(409, "barcode_decision_mismatch", "The change rules and the renderer decided differently.",
                       {"change_rules": outcome.decision, "renderer": revision.action})
    return Plan(
        artwork_id=new_id("art"), version_id=version_id, change_id=change_id, label_id=label_id,
        product_id=product_id, user_id=user.user_id, test_data=test_data,
        assessment_id=assessment.assessment_id if assessment else None, revision=revision,
        decision=_decision_json(outcome),
        change_log=_log_entries(session, user.user_id, edits, label_id, assessment, reason, outcome),
        base_product_version=base_row.version, reuse_product_version=applied.version if applied else None,
        template_id=template_row.template_id, template_version=template_row.version,
        qr_payload=f"{public_base_url()}/versions/{version_id}",
    )


def _payload(values: dict[str, str]) -> str:
    try:
        return build_payload(values)
    except ValueError:
        return ""


_REFUSALS = (  # start of a renderer message -> (status, code)
    ("Stale change", (409, "stale_change")), ("Change does not alter", (422, "no_change")),
    ("Only background=null", (422, "template_background_unsupported")),
    ("product_incomplete", (422, "product_incomplete")),
)


def _refusal(error: ValueError) -> ApiError:
    """Turn a renderer ValueError that is not a layout failure into a contract error."""
    message = str(error)
    for start, (status, code) in _REFUSALS:
        if message.startswith(start):
            return ApiError(status, code, message)
    return ApiError(422, "generation_refused", message)


def _log_entries(
    session: Session, user_id: str, edits: list[dict[str, str]], label_id: str, assessment: ChangeAssessment | None,
    reason: str, outcome: BarcodeOutcome,
) -> list[dict[str, Any]]:
    """Contract ChangeLogEntry rows: who changed which field, which rules fired, which passages back it."""
    items = [i for i in (assessment.payload["items"] if assessment else []) if i["label_id"] == label_id]
    entries = []
    for edit in edits:
        related = [i for i in items if edit["field"] in (i.get("fields") or [edit["field"]])]
        rules = list(dict.fromkeys(r for i in related for r in i.get("rule_ids", [])))
        if edit["field"] in ENCODED_FIELDS:
            rules = list(dict.fromkeys([*rules, *outcome.rule_ids]))
        evidence = list(dict.fromkeys(c for i in related for c in i.get("evidence_chunk_ids", [])))
        entry: dict[str, Any] = {
            "at": utcnow(), "user_id": user_id, "field": edit["field"], "old_value": edit["old_value"],
            "new_value": edit["new_value"], "reason": reason,
        }
        if rules:
            entry["rules_fired"] = rules
        if evidence:
            entry["evidence_chunk_ids"] = evidence
        entries.append(entry)
    return entries


# ---------------------------------------------------------------- the background job


def _report(plan: Plan, art: GeneratedArtwork, shas: dict[str, str], rendered: Any) -> dict[str, Any]:
    """The report stored with the draft: hashes, markings, decision, change log and the scope of the self-check."""
    return {
        "report_version": 1, "version_id": plan.version_id, "label_id": plan.label_id, "change_id": plan.change_id,
        "assessment_id": plan.assessment_id, "artwork_id": plan.artwork_id, "status": "DRAFT",
        "created_at": art.created_at, "created_by": plan.user_id, "test_data": plan.test_data,
        "visible_markings": list(rendered.visible_markings), "reference_sha256": rendered.reference_sha256,
        "artifact_sha256": shas["pdf"], "pdf_sha256": shas["pdf"], "svg_sha256": shas["svg"],
        "qr": {"payload": plan.qr_payload, "png_sha256": shas["qr_png"], "svg_sha256": shas["qr_svg"], "live": False,
               "note": "Supplementary link. The page does not exist until the version is approved and published."},
        "barcode_decision": plan.decision, "change_log": plan.change_log,
        "self_check": plan.revision.self_check, "disclaimer": DISCLAIMER,
    }


def run_generate_job(app: Any, job_id: str, plan: Plan) -> None:
    """Background body of a 202 generate: render, store the files, append every row in one transaction."""
    with app.state.session_factory() as session:
        try:
            checks.advance_job(session, job_id, "processing", 0.2, "rendering the label")
            root = artifacts_root(checks.files_dir())
            with tempfile.TemporaryDirectory(dir=root, prefix=".render-") as scratch:
                rendered = app.state.artwork_engine.render(plan.revision, Path(scratch), plan.qr_payload)
            checks.advance_job(session, job_id, "processing", 0.6, "storing the files")
            shas = {
                "pdf": store_file(root, rendered.pdf, "pdf"), "svg": store_file(root, rendered.svg, "svg"),
                "qr_png": store_file(root, rendered.qr_png, "png"), "qr_svg": store_file(root, rendered.qr_svg, "svg"),
            }
            now = utcnow()
            art = GeneratedArtwork(
                artwork_id=plan.artwork_id, change_id=plan.change_id, label_id=plan.label_id,
                version_id=plan.version_id, assessment_id=plan.assessment_id, self_check_id="",
                artifact_sha256=shas["pdf"],
                reference_sha256=rendered.reference_sha256, test_data=plan.test_data, size_w=rendered.size_mm[0],
                size_h=rendered.size_mm[1], barcode_decision=plan.decision, change_log=plan.change_log,
                visible_markings=list(rendered.visible_markings), created_by=plan.user_id, created_at=now,
            )
            report = json.dumps(_report(plan, art, shas, rendered), indent=2, sort_keys=True).encode("utf-8")
            shas["report"] = store_file(root, report, "json")
            _append_rows(session, plan, art, shas, rendered, {"report": len(report)})
            checks.advance_job(session, job_id, "done", 1.0, result_url=f"/artworks/{plan.artwork_id}")
        except ApiError as error:
            session.rollback()
            checks.advance_job(session, job_id, "failed", 1.0, error=error.body())
        except LayoutFailure as failure:
            session.rollback()
            error = {"error": "layout_failed", "message": failure.message}
            checks.advance_job(session, job_id, "failed", 1.0, error=error)
        except RendererUnavailable as unavailable:
            session.rollback()
            error = {"error": "renderer_unavailable", "message": str(unavailable)}
            checks.advance_job(session, job_id, "failed", 1.0, error=error)
        except Exception as error:  # a job must end in a state a client can read
            session.rollback()
            message = f"{type(error).__name__}: {error}"
            checks.advance_job(session, job_id, "failed", 1.0, error={"error": "generation_failed", "message": message})


def _append_rows(
    session: Session, plan: Plan, art: GeneratedArtwork, shas: dict[str, str], rendered: Any,
    extra_sizes: dict[str, int],
) -> None:
    """Append product version, template version, label version, layout check, artwork and files, then commit once."""
    user = plan.user_id
    current = _current_product(session, plan.product_id)
    if plan.reuse_product_version is None:
        if current.version != plan.base_product_version:
            message = "The product record changed while the draft was being made. Generate again."
            raise ApiError(409, "product_changed", message)
        record = plan.revision.record
        values = {f: getattr(record, f) for f in PRODUCT_RECORD_FIELDS}
        product = add_product_version(session, user, plan.product_id, values, plan.change_id, commit=False)
        product_version = product.version
    else:
        product_version = plan.reuse_product_version
    latest_template = session.scalars(select(LabelTemplate).where(
        LabelTemplate.template_id == plan.template_id).order_by(LabelTemplate.version.desc())).first()
    if latest_template is None or latest_template.version != plan.template_version:
        raise ApiError(409, "template_changed", "The template changed while the draft was being made. Generate again.")
    new_template = plan.revision.template
    template = register_template(
        session, user, plan.product_id, {"w": new_template["size_mm"]["w"], "h": new_template["size_mm"]["h"]},
        [dict(s) for s in new_template["slots"]], None, new_template.get("min_font_pt"), plan.template_id,
        commit=False,
    )
    if template.version != new_template["version"]:
        raise ApiError(409, "template_changed", "The template version changed while the draft was being made.")
    version = add_label_version(
        session, user, plan.product_id, f"{ARTIFACT_DIR}/{shas['svg']}.svg", kind="generated", label_id=plan.label_id,
        product_version=product_version, template_id=plan.template_id, template_version=template.version,
        pdf_file=f"{ARTIFACT_DIR}/{shas['pdf']}.pdf", change_id=plan.change_id, artifact_sha256=shas["pdf"],
        version_id=plan.version_id, commit=False,
    )
    layout = add_check_result(
        session, "layout", [], version_id=version.version_id, template_id=plan.template_id,
        artifact_sha256=shas["pdf"], user_id=user, commit=False,
    )
    art.self_check_id = layout.check_id
    session.add(art)
    sizes = {"pdf": len(rendered.pdf), "svg": len(rendered.svg), "qr_png": len(rendered.qr_png),
             "qr_svg": len(rendered.qr_svg), **extra_sizes}
    for role, (ext, mime) in ROLE_FILE.items():
        session.add(Artifact(
            sha256=shas[role], version_id=version.version_id, role=role, mime=mime, ext=ext,
            size_bytes=sizes[role], created_at=art.created_at,
        ))
    record_audit(
        session, user, "artwork.generated", "label_version", version.version_id,
        details={"artwork_id": plan.artwork_id, "change_id": plan.change_id, "artifact_sha256": shas["pdf"],
                 "barcode_decision": plan.decision["decision"], "test_data": plan.test_data},
        at=art.created_at,
    )
    session.commit()


# ---------------------------------------------------------------- reads


def _files(session: Session, version_id: str) -> dict[str, Artifact]:
    return {a.role: a for a in session.scalars(select(Artifact).where(Artifact.version_id == version_id))}


def artwork_json(session: Session, row: GeneratedArtwork) -> dict[str, Any]:
    """Contract GeneratedArtwork."""
    version = session.scalars(select(LabelVersion).where(LabelVersion.version_id == row.version_id)).one()
    files = _files(session, row.version_id)
    return {
        "artwork_id": row.artwork_id, "change_id": row.change_id, "label_id": row.label_id,
        "version_id": row.version_id, "template_id": version.template_id, "template_version": version.template_version,
        "svg_url": f"/artifacts/{files['svg'].sha256}", "pdf_url": f"/artifacts/{files['pdf'].sha256}",
        "size_mm": {"w": row.size_w, "h": row.size_h}, "draft_watermark": True, "test_data": row.test_data,
        "barcode_decision": row.barcode_decision, "change_log": row.change_log, "layout_problems": [],
        "self_check_id": row.self_check_id, "artifact_sha256": row.artifact_sha256, "disclaimer": DISCLAIMER,
    }


def export_json(session: Session, version: LabelVersion) -> dict[str, Any]:
    """Contract ExportPackage for one generated version. The files are the stored drafts, mark included."""
    art = session.scalars(select(GeneratedArtwork).where(GeneratedArtwork.version_id == version.version_id)).first()
    files = _files(session, version.version_id)
    if art is None or not files:
        raise ApiError(404, "no_artifacts", "This version has no generated files. Only generated artwork exports.")
    size = {"w": art.size_w, "h": art.size_h}
    out: dict[str, Any] = {
        "label_id": version.label_id, "version_id": version.version_id,
        "status": label_version_status(session, version.version_id),
        "draft_watermark": True if art.visible_markings else _derived_watermark(session, version.version_id),
        "pdf": {"url": f"/artifacts/{files['pdf'].sha256}", "mime": "application/pdf", "sha256": files["pdf"].sha256,
                "size_mm": size},
        "svg": {"url": f"/artifacts/{files['svg'].sha256}", "mime": "image/svg+xml", "sha256": files["svg"].sha256,
                "size_mm": size},
        "report": {"report_id": f"rpt_{files['report'].sha256[:8]}", "label_id": version.label_id,
                   "version_id": version.version_id, "url": f"/artifacts/{files['report'].sha256}",
                   "artifact_sha256": files["report"].sha256, "created_at": files["report"].created_at},
    }
    page = session.scalars(select(PublishedPage).where(PublishedPage.version_id == version.version_id)).first()
    if page is not None:
        out["qr"] = {"page_id": page.page_id, "label_id": page.label_id, "version_id": page.version_id,
                     "url": page.url, "qr_payload": page.qr_payload, "published_at": page.published_at,
                     "review_id": page.review_id}
    return out


def _derived_watermark(session: Session, version_id: str) -> bool:
    return label_version_status(session, version_id) not in ("reviewed", "published")


def download(session: Session, user: User, sha256: str) -> Response:
    """Serve one stored file by its hash, after re-hashing it (a changed or missing file is never served).

    The mark is part of the file itself. QR files are served only for a published version (the contract: no QR
    before publication). The response carries `X-Draft-Mark` whenever the file's version has visible markings.
    """
    rows = list(session.scalars(select(Artifact).where(Artifact.sha256 == sha256).order_by(Artifact.seq)))
    if not rows:
        raise ApiError(404, "not_found", f"No stored file with sha256 {sha256}.")
    row = rows[0]
    if row.role.startswith("qr") and session.scalars(
        select(PublishedPage.page_id).where(PublishedPage.version_id == row.version_id)
    ).first() is None:
        raise ApiError(409, "not_published", "The QR is available only for a published version.")
    path = checks.files_dir() / ARTIFACT_DIR / f"{row.sha256}.{row.ext}"
    if not path.is_file():
        raise ApiError(404, "artifact_missing", "The stored file is missing on the server.")
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != row.sha256:
        raise ApiError(500, "artifact_corrupt", "The stored file does not match its hash and was not served.")
    art = session.scalars(select(GeneratedArtwork).where(GeneratedArtwork.version_id == row.version_id)).first()
    headers = {
        "Content-Disposition": f'attachment; filename="{row.version_id}.{row.role}.{row.ext}"',
        "X-Content-Type-Options": "nosniff", "Cache-Control": "private, max-age=31536000, immutable",
        "Content-Security-Policy": "default-src 'none'; style-src 'unsafe-inline'; img-src data:",
        "X-Label-Version": row.version_id, "X-Artifact-Sha256": row.sha256,
    }
    if art is not None and art.visible_markings:
        headers["X-Draft-Mark"] = " | ".join(art.visible_markings)
    record_audit(session, user.user_id, "export.downloaded", "label_version", row.version_id,
                 details={"sha256": row.sha256, "role": row.role})
    session.commit()
    return Response(content=data, media_type=row.mime, headers=headers)
