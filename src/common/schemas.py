"""Shared data contracts. Lock these on Day 1. Change only through a PR all 3 approve."""
from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, Field


class Chunk(BaseModel):
    chunk_id: str
    source: str
    url: str = ""
    title: str = ""
    section: str = ""
    text: str
    fetched: str = ""
    hash: str = ""
    module: Literal["device", "medicine"] = "device"


class Hit(BaseModel):
    doc_id: str
    score: float
    rank: int = 0
    text: str = ""


class OcrBlock(BaseModel):
    text: str
    bbox: tuple[float, float, float, float]
    conf: float = 0.0


class BarcodeResult(BaseModel):
    type: str
    raw: str
    parsed: dict[str, str] = Field(default_factory=dict)
    bbox: Optional[tuple[float, float, float, float]] = None


class SymbolDetection(BaseModel):
    name: str
    iso_ref: str = ""
    bbox: tuple[float, float, float, float]
    conf: float = 0.0


class LabelExtraction(BaseModel):
    label_id: str
    version: int = 1
    fields: dict[str, str] = Field(default_factory=dict)
    warnings: list[str] = Field(default_factory=list)
    barcodes: list[BarcodeResult] = Field(default_factory=list)
    symbols: list[SymbolDetection] = Field(default_factory=list)
    ocr_blocks: list[OcrBlock] = Field(default_factory=list)


class ProductRecord(BaseModel):
    product_id: str
    version: int = 1
    name: str
    model: str = ""
    manufacturer: str = ""
    manufacturer_address: str = ""
    udi_di: str = ""  # allocated by the company, never generated by LabelLens
    sterilization: str = ""
    storage: str = ""
    extra: dict[str, str] = Field(default_factory=dict)


class Flag(BaseModel):
    flag_id: str
    kind: str  # e.g. field_mismatch, barcode_mismatch, missing_symbol, missing_warning
    severity: Literal["info", "review", "critical"] = "review"
    message: str
    observed: str = ""
    expected: str = ""
    evidence_chunk_ids: list[str] = Field(default_factory=list)
    confidence: float = 0.0
    needs_human: bool = True


class ChangeRequest(BaseModel):
    change_id: str
    product_id: str
    field: str
    old_value: str = ""
    new_value: str
    status: Literal["draft", "checked", "reviewed", "published"] = "draft"


class IdentifierRequired(Exception):
    """Raised when a change needs a new GTIN or UDI-DI that must be entered by a human."""
